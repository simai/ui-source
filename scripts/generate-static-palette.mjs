#!/usr/bin/env node
// Writes the static palette's CSS primitives (owner decision C17, 2026-11-08)
// from the generator itself, src/core/js/theme-palette.js: sixteen fixed hues,
// each the sixteen tones THEME_TONES and the translucent steps STATIC_ALPHA,
// --sf-<hue>-<tone> and --sf-<hue>-<tone>--alfa-<n>. No value in the output is
// typed by hand.
//
//   node scripts/generate-static-palette.mjs          write the file
//   node scripts/generate-static-palette.mjs --check  fail if it is stale
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {STATIC_HUES, STATIC_ALPHA, THEME_TONES, staticPalette} from '../src/core/js/theme-palette.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const STATIC_PALETTE_FILE = 'src/core/scss/_sf_static_palette.scss';

export function staticPaletteScss() {
  const palettes = staticPalette();
  const alphaHex = (percent) => Math.round((percent * 255) / 100).toString(16).padStart(2, '0');
  const lines = [
    '// Generated by scripts/generate-static-palette.mjs from src/core/js/theme-palette.js',
    '// (STATIC_HUES, STATIC_ALPHA); do not edit. Owner decision C17, 2026-11-08.',
    '@layer sf.base {',
    '  /* The static palette: sixteen fixed hues through the theme\'s own generator',
    '     (HCT TonalPalette), the same tones and translucent steps for every hue.',
    '     No theme colour moves them; a status primitive (--sf-error-<tone>,',
    '     --sf-warning-, --sf-success-, --sf-info-) is var() of its hue. */',
    '  :root {',
  ];
  for (const [name, {hue, chroma}] of Object.entries(STATIC_HUES)) {
    lines.push(`    /* ${name}: HCT hue ${hue}, chroma ${chroma} */`);
    for (const tone of THEME_TONES) {
      const value = palettes[name].tones[tone];
      lines.push(`    --sf-${name}-${tone}: ${value};`);
      for (const step of STATIC_ALPHA[tone] ?? []) lines.push(`    --sf-${name}-${tone}--alfa-${step}: ${value}${alphaHex(step)};`);
    }
  }
  lines.push('  }', '}', '');
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const path = resolve(root, STATIC_PALETTE_FILE);
  const wanted = staticPaletteScss();
  if (process.argv.includes('--check')) {
    const actual = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (actual !== wanted) {
      process.stderr.write(`${STATIC_PALETTE_FILE} is stale: run node scripts/generate-static-palette.mjs\n`);
      process.exit(1);
    }
    process.stdout.write(`${STATIC_PALETTE_FILE} is current\n`);
  } else {
    writeFileSync(path, wanted);
    process.stdout.write(`wrote ${STATIC_PALETTE_FILE}\n`);
  }
}
