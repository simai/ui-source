#!/usr/bin/env node
// Usage: node scripts/build-first-paint-kit.mjs [--check]
//
// The first-paint render tool as the pair ships it (docs/developer/
// first-paint-render.md). The pair's distr/ carries the source modules of
// core/js/composition/ as they are, and every file they import (ui-builder
// materializeSourceAssets), so the tool ships there:
//
//   src/core/js/composition/first-paint-render.mjs   the entry: the command line
//                                                    and the module API
//   src/core/js/composition/first-paint/render.mjs   tools/first-paint/render.mjs, as is
//   src/core/js/composition/first-paint/engine.mjs   tools/first-paint/kit-engine.mjs, as is
//   src/core/js/composition/first-paint/lib.mjs      scripts/first-paint-lib.mjs, as is
//   src/core/js/composition/first-paint/page.mjs     the text of scripts/first-paint-page.js
//
// One source: the files are written from the tools, never edited. --check
// writes nothing and fails when a written file is not what the tools give
// (tests/first-paint-render.contract.test.mjs runs it).
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const kit = join(repo, 'src', 'core', 'js', 'composition');
const read = (path) => readFileSync(join(repo, path), 'utf8');
const header = (source) => `// Generated by scripts/build-first-paint-kit.mjs from ${source}: do not edit; edit the source and run it again.\n`;
// A copied module keeps every byte of its source after its first line when
// that is a #! line (an entry's own is written below).
const asIs = (source) => header(source) + read(source).replace(/^#![^\n]*\n/u, '');

export function kitFiles() {
  return new Map([
    ['first-paint-render.mjs', `#!/usr/bin/env node
${header('scripts/build-first-paint-kit.mjs')}// The first paint of a Smart component from its settings
// (simai.first-paint-render.v1, docs/developer/first-paint-render.md):
//
//   node <distr>/core/js/composition/first-paint-render.mjs --session < requests.jsonl
//
// --distr defaults to the distr/ this file is in.
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {main} from './first-paint/render.mjs';

export * from './first-paint/render.mjs';

const distr = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? '')).href) {
  process.exitCode = await main(process.argv.slice(2), {defaults: {distr}});
}
`],
    ['first-paint/render.mjs', asIs('tools/first-paint/render.mjs')],
    ['first-paint/engine.mjs', asIs('tools/first-paint/kit-engine.mjs')],
    ['first-paint/lib.mjs', asIs('scripts/first-paint-lib.mjs')],
    ['first-paint/page.mjs', `${header('scripts/first-paint-page.js')}// The page script of every first-paint page, as text: served to the page as
// /first-paint-page.js, never run in Node.
export default ${JSON.stringify(read('scripts/first-paint-page.js'))};
`],
  ]);
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? '')).href) {
  const check = process.argv.includes('--check');
  const stale = [];
  const written = [];
  for (const [name, body] of kitFiles()) {
    const file = join(kit, name);
    const now = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (now === body) continue;
    if (check) {
      stale.push(relative(repo, file));
      continue;
    }
    mkdirSync(dirname(file), {recursive: true});
    writeFileSync(file, body);
    written.push(relative(repo, file));
  }
  console.log(JSON.stringify({mode: check ? 'check' : 'write', files: kitFiles().size, stale, written}, null, 2));
  if (stale.length) process.exit(1);
}
